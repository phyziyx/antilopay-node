  /**
   * Check whether a Steam account can be topped up.
   * @param steamAccountId The login of the Steam account to top up.
   * @returns {Promise<boolean>} `true` when the account was found and can be
   * topped up (HTTP 200), `false` when it cannot be topped up (HTTP 404).
   * @throws {AntilopayApiError} On HTTP 400 (missing data), 403 (access
   * denied), 500 (server error) or any other unexpected failure. The HTTP
   * status is exposed as `apiCode`.
   */
  public async checkSteamAccount(steamAccountId: string): Promise<boolean> {
    const payload = {
      project_identificator: this.projectId,
      steam_account: steamAccountId,
    };

    try {
      await this.post(`/steam/account/check`, payload);
      return true;
    } catch (error) {
      if (error instanceof AntilopayApiError && error.apiCode === 404) {
        return false;
      }

      throw error;
    }
  }

