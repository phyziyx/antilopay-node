  /**
   * Get the API headers for the API.
   * @param payload The payload to sign, when a signature is required.
   * @param signingKey The private key used to sign the payload.
   * @returns
   */
  private getApiHeaders(
    payload?: object,
    signingKey?: string,
  ): Record<string, string | number> {
    let signature = '';

    if (payload) {
      signature = this.generateSignature(payload, signingKey);
    }

    return {
      'Content-Type': 'application/json',
      Accept: 'application/json',
      'X-Apay-Secret-Id': this.secretId,
      ...(payload
        ? {
            'X-Apay-Sign-Version': this.signingVersion,
            'X-Apay-Sign': signature,
          }
        : {}),
    };
  }

  /**
   * Generate the signature for the API request.
   * This is used to authenticate the request with the Antilopay API.
   * @param payload The payload to sign, must a JSON object.
   * @param signingKey The private key to sign with, defaults to the merchant secret key.
   * @returns The signature for the API request.
   */
  private generateSignature(payload: object, signingKey?: string): string {
    const data = JSON.stringify(payload);

    const signature = crypto.createSign(this.signingAlgorithm);
    signature.update(data);
    signature.end();

    const sign = signature.sign(
      signingKey ?? this.secretKey,
      this.signingAlgorithmOutput,
    );
    return sign;
  }

  /**
   * Verify the signature for the API request locally.
   * @param payload The payload to verify, must be a JSON object.
   * @param signature The signature to verify, found in header as 'X-Apay-Callback'.
   * @returns {boolean} True if the signature is valid, false otherwise.
   */
  public async verifySignature(
    payload: object,
    signature: string,
  ): Promise<boolean> {
    const data = JSON.stringify(payload);

    const verify = crypto.createVerify(this.signingAlgorithm);
    verify.update(data);
    verify.end();

    return verify.verify(
      this.callbackKey,
      signature,
      this.signingAlgorithmOutput,
    );
  }

