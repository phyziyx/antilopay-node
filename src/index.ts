export class AntilopayError extends Error {}

/**
 * Thrown when Antilopay API responds with a non-success code or when an HTTP
 * transport error occurs. Contains the API `code`, a message and the raw data.
 */
export class AntilopayApiError extends AntilopayError {
  public readonly apiCode: number;
  public readonly apiMessage: string;
  public readonly data: any;
  /**
   * The value of the `X-Apay-Request-Id` response header, when present.
   * Reference it when contacting technical support.
   */
  public readonly requestId?: string | undefined;

  constructor(apiCode: number, message: string, data: any, requestId?: string) {
    super(message);

    this.apiCode = apiCode;
    this.apiMessage = message;
    this.data = data;
    this.requestId = requestId;

    // Set the prototype explicitly to maintain instanceof checks
    Object.setPrototypeOf(this, AntilopayApiError.prototype);
  }
}

/**
 * Thrown when the signature verification for a webhook fails.
 * Indicates that the webhook may not be legitimate!
 */
export class AntilopaySignatureError extends AntilopayError {
  constructor() {
    super('Invalid signature');
  }
}

